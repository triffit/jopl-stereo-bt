use generated::{ErrorWindow, MainWindow};

/// How often the window refreshes from the engine.
const REFRESH: Duration = Duration::from_millis(100);

/// Runs the main window until it is closed, then saves settings.
pub(crate) fn run_main<E, S>(engine: E, store: S) -> Result<(), slint::PlatformError>
where
    E: EngineControl + 'static,
    S: SettingsStore + 'static,
{
    select_backend()?;
    let window = MainWindow::new()?;
    apply_system_accent(&window);
    window.set_version(env!("CARGO_PKG_VERSION").into());
    let controller = Rc::new(RefCell::new(Controller::new(engine, store)));
    let rows = Rc::new(VecModel::<generated::DeviceRow>::default());
    window.set_devices(ModelRc::from(Rc::clone(&rows)));

    let bind = Binder {
        controller: Rc::clone(&controller),
        window: window.as_weak(),
        rows: Rc::clone(&rows),
    };
    window.on_toggle_running(bind.action(Controller::toggle_running));
    window.on_checked_changed(bind.device(|c, id, on: bool| c.set_enabled(id, on)));
    window.on_ping(bind.device_action(Controller::ping));
    window.on_position_changed(
        bind.device(|c, id, index: i32| c.set_position(id, position_from_index(index))),
    );
    window
        .on_collapsed_changed(bind.device(|c, id, collapsed: bool| c.set_collapsed(id, collapsed)));
    window.on_make_default(bind.device_action(Controller::make_default));
    window.on_measure_start(bind.action(Controller::start_measurement));
    window.on_measure_apply(bind.action(Controller::measurement_apply));
    window.on_measure_close(bind.action(Controller::measurement_close));
    window.on_assistant_start(bind.action(|c| c.start_assistant(Instant::now())));
    window.on_assistant_tap(bind.action(|c| c.assistant_tap(Instant::now())));
    window.on_assistant_next(bind.action(Controller::assistant_next));
    window.on_assistant_restart(bind.action(Controller::assistant_restart_step));
    window.on_assistant_apply(bind.action(Controller::assistant_apply));
    window.on_assistant_close(bind.action(Controller::assistant_close));
    window.on_unmute_app({
        let bind = bind.clone();
        move |pid| {
            if let Ok(pid) = u32::try_from(pid) {
                bind.controller.borrow_mut().unmute_app(pid);
                bind.refresh();
            }
        }
    });
    window.on_include_default_changed(bind.flag(Controller::set_include_default));
    window.on_keep_streaming_changed(bind.flag(Controller::set_keep_streaming_on_close));
    window.on_follow_system_volume_changed(bind.flag(Controller::set_follow_system_volume));
    window.on_mode_changed(
        bind.device(|c, id, mode: i32| c.set_channel_mode(id, mode_from_index(mode))),
    );
    window.on_delay_changed(bind.device(|c, id, millis: f32| c.set_delay(id, round(millis))));
    window.on_volume_changed(bind.device(|c, id, percent: f32| c.set_volume(id, round(percent))));
    window.on_stereo_width_changed(bind.action_with(|c, v: f32| c.set_stereo_width(round(v))));
    window.on_reverb_changed(bind.action_with(|c, v: f32| c.set_reverb(round(v))));
    window.on_room_size_changed(bind.action_with(|c, v: f32| c.set_room_size(round(v))));
    window.on_bass_cut_changed(bind.device(|c, id, hz: f32| c.set_bass_cut(id, round(hz))));
    window.on_virtual_bass_changed(
        bind.device(|c, id, percent: f32| c.set_virtual_bass(id, round(percent))),
    );
    window.on_max_volume_changed(
        bind.device(|c, id, percent: f32| c.set_max_volume(id, round(percent))),
    );

    // Without a tray (e.g. no taskbar) the app cannot be reached when hidden,
    // so closing the window then always quits.
    let tray = Rc::new(RefCell::new(crate::tray::Tray::new().ok()));

    window.window().on_close_requested({
        let controller = Rc::clone(&controller);
        let tray = Rc::clone(&tray);
        move || {
            let keep_streaming = {
                let controller = controller.borrow();
                controller.is_running()
                    && controller.keeps_streaming_on_close()
                    && tray.borrow().is_some()
            };
            if !keep_streaming {
                // The event loop keeps running for the tray; end it explicitly.
                let _ = slint::quit_event_loop();
            }
            slint::CloseRequestResponse::HideWindow
        }
    });

    let timer = Timer::default();
    timer.start(TimerMode::Repeated, REFRESH, {
        let bind = bind.clone();
        let tray = Rc::clone(&tray);
        move || {
            bind.controller.borrow_mut().tick(Instant::now());
            if let Some(tray) = tray.borrow_mut().as_mut() {
                for action in tray.poll() {
                    handle_tray_action(&bind, action);
                }
                tray.set_running(bind.controller.borrow().is_running());
            }
            bind.refresh();
        }
    });
    bind.refresh();

    window.show()?;
    slint::run_event_loop_until_quit()?;
    timer.stop();
    controller.borrow_mut().save();
    Ok(())
}

fn handle_tray_action<E, S>(bind: &Binder<E, S>, action: crate::tray::TrayAction)
where
    E: EngineControl + 'static,
    S: SettingsStore + 'static,
{
    use crate::tray::TrayAction;
    match action {
        TrayAction::Show => {
            if let Some(window) = bind.window.upgrade() {
                // Showing an already visible window is harmless.
                let _ = window.show();
                window.window().set_minimized(false);
            }
        }
        TrayAction::ToggleRunning => bind.controller.borrow_mut().toggle_running(),
        TrayAction::Quit => {
            let _ = slint::quit_event_loop();
        }
    }
}

/// Uses the winit backend with a dark title bar and the Windows 11 Mica
/// backdrop behind the whole window (title bar included), which shows
/// through the transparent window background, as in Windows Settings.
/// Older Windows versions ignore what they do not support and keep the solid look.
fn select_backend() -> Result<(), slint::PlatformError> {
    use slint::winit_030::winit::platform::windows::{BackdropType, WindowAttributesExtWindows};
    use slint::winit_030::winit::window::Theme;

    slint::BackendSelector::new()
        .backend_name("winit".into())
        .with_winit_window_attributes_hook(|attributes| {
            attributes
                .with_theme(Some(Theme::Dark))
                .with_system_backdrop(BackdropType::MainWindow)
                .with_transparent(true)
        })
        .select()
}

/// Uses the user's Windows accent colour, as Windows Settings does.
fn apply_system_accent(window: &MainWindow) {
    if let Some(accent) = crate::accent::system_accent() {
        let theme = window.global::<generated::Theme>();
        let color = slint::Color::from_rgb_u8(accent.r, accent.g, accent.b);
        theme.set_accent(color);
        // Windows uses the same shade at 90 % opacity for hover.
        theme.set_accent_hover(color.with_alpha(0.9));
    }
}

/// Shows a fatal start-up error.
pub(crate) fn show_error(message: &str) -> Result<(), slint::PlatformError> {
    let window = ErrorWindow::new()?;
    window.set_message(message.into());
    let weak = window.as_weak();
    window.on_close_requested(move || {
        if let Some(window) = weak.upgrade() {
            // Hiding the only window ends the event loop.
            let _ = window.hide();
        }
    });
    window.run()
}

/// Shared handles every callback needs.
struct Binder<E: EngineControl, S: SettingsStore> {
    controller: Rc<RefCell<Controller<E, S>>>,
    window: slint::Weak<MainWindow>,
    rows: Rc<VecModel<generated::DeviceRow>>,
}

impl<E: EngineControl, S: SettingsStore> Clone for Binder<E, S> {
    fn clone(&self) -> Self {
        Self {
            controller: Rc::clone(&self.controller),
            window: self.window.clone(),
            rows: Rc::clone(&self.rows),
        }
    }
}

impl<E: EngineControl + 'static, S: SettingsStore + 'static> Binder<E, S> {
    fn action(&self, apply: impl Fn(&mut Controller<E, S>) + 'static) -> impl Fn() + 'static {
        let bind = self.clone();
        move || {
            apply(&mut bind.controller.borrow_mut());
            bind.refresh();
        }
    }

    /// A callback naming a device; the identifier comes from the UI and is validated.
    fn device_action(
        &self,
        apply: impl Fn(&mut Controller<E, S>, &DeviceId) + 'static,
    ) -> impl Fn(SharedString) + 'static {
        let bind = self.clone();
        move |raw_id| {
            if let Ok(id) = DeviceId::new(raw_id.as_str()) {
                apply(&mut bind.controller.borrow_mut(), &id);
                bind.refresh();
            }
        }
    }

    /// A callback with one value, e.g. a slider.
    fn action_with<T>(
        &self,
        apply: impl Fn(&mut Controller<E, S>, T) + 'static,
    ) -> impl Fn(T) + 'static {
        let bind = self.clone();
        move |value| {
            apply(&mut bind.controller.borrow_mut(), value);
            bind.refresh();
        }
    }

    /// A switch callback.
    fn flag(
        &self,
        apply: impl Fn(&mut Controller<E, S>, bool) + 'static,
    ) -> impl Fn(bool) + 'static {
        let bind = self.clone();
        move |on| {
            apply(&mut bind.controller.borrow_mut(), on);
            bind.refresh();
        }
    }

    /// A per-device callback; the identifier comes from the UI and is validated.
    fn device<T>(
        &self,
        apply: impl Fn(&mut Controller<E, S>, &DeviceId, T) + 'static,
    ) -> impl Fn(SharedString, T) + 'static {
        let bind = self.clone();
        move |raw_id, value| {
            if let Ok(id) = DeviceId::new(raw_id.as_str()) {
                apply(&mut bind.controller.borrow_mut(), &id, value);
                bind.refresh();
            }
        }
    }

    fn refresh(&self) {
        if let Some(window) = self.window.upgrade() {
            apply_view(&window, &self.rows, &self.controller.borrow().view());
        }
    }
}

fn apply_view(window: &MainWindow, rows: &VecModel<generated::DeviceRow>, view: &View) {
    window.set_running(view.running);
    let levels: Vec<i32> = view
        .levels
        .iter()
        .map(|level| level.map_or(-1, i32::from))
        .collect();
    window.set_levels(ModelRc::new(VecModel::from(levels)));
    window.set_stereo_width(f32::from(view.space.width.as_percent()));
    window.set_reverb(f32::from(view.space.reverb.get()));
    window.set_room_size(f32::from(view.space.room_size.get()));
    window.set_status_word(view.status_word.into());
    window.set_status_message(view.status_message.as_str().into());
    window.set_include_default(view.toggles.include_default);
    window.set_follow_system_volume(view.toggles.follow_system_volume);
    window.set_keep_streaming_on_close(view.toggles.keep_streaming_on_close);
    window.set_out_of_sync(view.out_of_sync > 0);
    window.set_measured_with(view.measured_with.as_deref().unwrap_or_default().into());
    apply_lanes(window, &view.lanes);
    apply_assistant(window, view.assistant.as_ref());
    apply_measurement(window, view.measurement.as_ref());
    match &view.muted_app {
        Some((text, pid)) => {
            window.set_muted_app_text(text.as_str().into());
            window.set_muted_app_pid(i32::try_from(*pid).unwrap_or(0));
        }
        None => window.set_muted_app_text(SharedString::new()),
    }
    window.set_system_volume_text(
        view.system_volume_percent
            .map(|percent| format!("{percent} %"))
            .unwrap_or_default()
            .into(),
    );
    window.set_status_kind(match view.status_kind {
        StatusKind::Idle => 0,
        StatusKind::Streaming => 1,
        StatusKind::Waiting => 2,
    });
    window.set_error_text(view.error.as_deref().unwrap_or_default().into());

    let first_target = view.rows.iter().position(|r| !r.is_source);
    let new_rows: Vec<generated::DeviceRow> = view
        .rows
        .iter()
        .enumerate()
        .map(|(index, row)| {
            let heading = if row.is_source {
                "Default device"
            } else if Some(index) == first_target {
                "Play on"
            } else {
                ""
            };
            to_ui_row(row, heading)
        })
        .collect();
    if rows.row_count() == new_rows.len() {
        // Update in place so focus and slider drags are not interrupted.
        for (index, row) in new_rows.into_iter().enumerate() {
            if rows.row_data(index).as_ref() != Some(&row) {
                rows.set_row_data(index, row);
            }
        }
    } else {
        rows.set_vec(new_rows);
    }
}

fn apply_lanes(window: &MainWindow, lanes: &[Lane]) {
    let axis = view_model::timeline(lanes);
    let ui_lanes: Vec<generated::Lane> = lanes
        .iter()
        .map(|lane| generated::Lane {
            name: lane.name.as_str().into(),
            own: to_f32(lane.own_ms),
            delay: f32::from(lane.delay_ms),
            plays: to_f32(lane.plays_ms),
            is_source: lane.is_source,
            in_sync: lane.in_sync,
        })
        .collect();
    let ticks: Vec<i32> = axis.ticks.iter().map(|&t| i32::from(t)).collect();
    window.set_lanes(ModelRc::new(VecModel::from(ui_lanes)));
    window.set_lane_ticks(ModelRc::new(VecModel::from(ticks)));
    window.set_lane_scale(to_f32(axis.scale_ms));
    window.set_lane_reference(to_f32(axis.reference_ms));
}

/// Milliseconds for drawing; precision beyond f32 is invisible on screen.
fn to_f32(ms: f64) -> f32 {
    #[allow(clippy::cast_possible_truncation)]
    let narrowed = ms as f32;
    narrowed
}

fn apply_assistant(window: &MainWindow, assistant: Option<&AssistantView>) {
    let Some(a) = assistant else {
        window.set_assistant(generated::AssistantState::default());
        return;
    };
    window.set_assistant(generated::AssistantState {
        active: true,
        phase: match a.phase {
            Phase::Measuring => 0,
            Phase::Results => 1,
            Phase::FineTune => 2,
        },
        step: to_i32(a.step),
        steps: to_i32(a.steps),
        device: a.device.as_str().into(),
        is_source: a.is_source,
        taps: to_i32(a.taps),
        taps_wanted: to_i32(a.taps_wanted),
        can_next: a.can_next,
    });
    let results: Vec<generated::AssistantResult> = a
        .results
        .iter()
        .map(|r| generated::AssistantResult {
            name: r.name.as_str().into(),
            text: r.text.as_str().into(),
            warning: r.warning,
        })
        .collect();
    window.set_assistant_results(ModelRc::new(VecModel::from(results)));
}

fn apply_measurement(window: &MainWindow, measurement: Option<&MeasureView>) {
    let (state, lines) = match measurement {
        None => (generated::MeasureState::default(), Vec::new()),
        Some(MeasureView::Running(text)) => (
            generated::MeasureState {
                active: true,
                phase: 0,
                text: text.as_str().into(),
                can_apply: false,
            },
            Vec::new(),
        ),
        Some(MeasureView::Done {
            lines,
            advice,
            can_apply,
        }) => (
            generated::MeasureState {
                active: true,
                phase: 1,
                text: advice.as_str().into(),
                can_apply: *can_apply,
            },
            lines
                .iter()
                .map(|l| SharedString::from(l.as_str()))
                .collect(),
        ),
        Some(MeasureView::Failed(text)) => (
            generated::MeasureState {
                active: true,
                phase: 2,
                text: text.as_str().into(),
                can_apply: false,
            },
            Vec::new(),
        ),
    };
    window.set_measure(state);
    window.set_measure_lines(ModelRc::new(VecModel::from(lines)));
}

fn to_i32(value: usize) -> i32 {
    i32::try_from(value).unwrap_or(i32::MAX)
}

fn to_ui_row(row: &DeviceRow, heading: &str) -> generated::DeviceRow {
    generated::DeviceRow {
        id: row.id.as_str().into(),
        name: row.name.as_str().into(),
        is_source: row.is_source,
        checked: row.checked,
        can_make_default: row.can_make_default,
        worn: view_model::looks_worn(&row.name),
        battery: row
            .battery_percent
            .map(|level| format!("{level} %"))
            .unwrap_or_default()
            .into(),
        battery_glyph: row
            .battery_percent
            .map(|level| view_model::battery_glyph(level).to_string())
            .unwrap_or_default()
            .into(),
        position: position_to_index(row.position),
        collapsed: row.collapsed,
        summary: row.summary.as_str().into(),
        battery_low: row
            .battery_percent
            .is_some_and(|level| level < view_model::LOW_BATTERY_PERCENT),
        heading: heading.into(),
        status: row.status.as_str().into(),
        tone: match row.tone {
            Tone::Neutral => 0,
            Tone::Good => 1,
            Tone::Caution => 2,
            Tone::Error => 3,
        },
        mode: mode_to_index(row.channel_mode),
        delay: f32::from(row.delay_ms),
        volume: f32::from(row.volume_percent),
        // The bass cut slider's lowest position (30) stands for off.
        bass_cut: if row.bass_cut_hz == 0 {
            30.0
        } else {
            f32::from(row.bass_cut_hz)
        },
        virtual_bass: f32::from(row.virtual_bass_percent),
        max_volume: f32::from(row.max_volume_percent),
    }
}

const fn position_to_index(position: SpeakerPosition) -> i32 {
    match position {
        SpeakerPosition::Front => 0,
        SpeakerPosition::Center => 1,
        SpeakerPosition::Rear => 2,
    }
}

const fn position_from_index(index: i32) -> SpeakerPosition {
    match index {
        1 => SpeakerPosition::Center,
        2 => SpeakerPosition::Rear,
        _ => SpeakerPosition::Front,
    }
}

const fn mode_to_index(mode: ChannelMode) -> i32 {
    match mode {
        ChannelMode::Stereo => 0,
        ChannelMode::LeftOnly => 1,
        ChannelMode::RightOnly => 2,
        ChannelMode::MonoMix => 3,
    }
}

const fn mode_from_index(index: i32) -> ChannelMode {
    match index {
        1 => ChannelMode::LeftOnly,
        2 => ChannelMode::RightOnly,
        3 => ChannelMode::MonoMix,
        _ => ChannelMode::Stereo,
    }
}

/// Rounds a slider value to whole units; the controller clamps the range.
fn round(value: f32) -> i64 {
    // Slider values are within 0..=500, far inside i64 and f32 exact-integer range.
    #[allow(clippy::cast_possible_truncation)]
    let rounded = value.round() as i64;
    rounded
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn channel_mode_index_round_trips() {
        for mode in [
            ChannelMode::Stereo,
            ChannelMode::LeftOnly,
            ChannelMode::RightOnly,
            ChannelMode::MonoMix,
        ] {
            assert_eq!(mode_from_index(mode_to_index(mode)), mode);
        }
    }

    #[test]
    fn position_index_round_trips() {
        for position in [
            SpeakerPosition::Front,
            SpeakerPosition::Center,
            SpeakerPosition::Rear,
        ] {
            assert_eq!(position_from_index(position_to_index(position)), position);
        }
    }

    #[test]
    fn slider_values_round_to_whole_units() {
        assert_eq!(round(119.6), 120);
        assert_eq!(round(0.4), 0);
    }
}
